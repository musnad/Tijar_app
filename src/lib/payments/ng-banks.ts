function uniqueBanks(rows: NgBank[]): NgBank[] {
  const seen = new Set<string>();
  const out: NgBank[] = [];
  for (const row of rows) {
    const code = row.code.trim();
    const name = row.name.trim();
    if (!code || !name || seen.has(code) || /[?]/.test(name)) continue;
    seen.add(code);
    out.push({ code, name });
  }
  return out;
}

const CLEAN = uniqueBanks(ALL_NG_BANKS);

export const NG_BANKS: NgBank[] = [
  ...POPULAR_CODES.map((code) => CLEAN.find((row) => row.code === code)).filter((row): row is NgBank => Boolean(row)),
  ...CLEAN.filter((row) => !(POPULAR_CODES as readonly string[]).includes(row.code)).sort((a, b) =>
    a.name.localeCompare(b.name),
  ),
];

export function ngBankName(code: string | null | undefined): string {
  if (!code) return "Bank";
  return NG_BANKS.find((row) => row.code === code)?.name ?? "Bank";
}

export function banksMatching(query: string): NgBank[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return NG_BANKS;
  return NG_BANKS.filter(
    (row) => row.name.toLowerCase().includes(needle) || row.code.includes(needle.replace(/\s+/g, "")),
  );
}
